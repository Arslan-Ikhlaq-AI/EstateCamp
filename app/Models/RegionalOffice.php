<?php

namespace App\Models;

use Database\Factories\RegionalOfficeFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

/**
 * One of a company's regional sub-offices, between the head office and its
 * camps and buildings. Switched off, it stays on the staff already placed
 * there but is no longer offered.
 */
#[Fillable(['name', 'code', 'city', 'address', 'phone', 'is_active'])]
class RegionalOffice extends Model
{
    /** @use HasFactory<RegionalOfficeFactory> */
    use HasFactory;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'is_active' => 'boolean',
        ];
    }

    /**
     * @return BelongsTo<Company, $this>
     */
    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    /**
     * @return HasMany<StaffMember, $this>
     */
    public function staffMembers(): HasMany
    {
        return $this->hasMany(StaffMember::class);
    }
}
